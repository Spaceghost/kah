require_relative "native"
require_relative "lua_emitter"
require_relative "../build/kah-native/runtime"

class KahCLI
  def initialize
    @source = ""
    @output = ""
    @inline = ""
    @inline_used = false
    @run = false
    @stdout = false
    @force = false
    @target = "lua"
    @interpreter = ""
    @run_args = []
    @load_paths = []
  end
  def usage
    puts "Kah 0.2.0 — Ruby/Spinel + Nelua, with Prism"
    puts "Usage: kah app.rb -o app.lua"
    puts "       kah -E app.rb [arguments]"
    puts "       kah --target=luajit -E app.rb"
    puts "       kah -e 'puts 42'"
    puts "Options: -o FILE, -S, -E, -e SOURCE, -I DIR, --target=lua|luajit, --lua=PATH, --force"
    puts "Compiler options precede the Ruby file when using -E."
  end
  def bad(message)
    STDERR.puts "kah: #{message}"
    2
  end
  def execute(args)
    i = 0
    while i < args.length
      arg = args[i]
      if arg == "--version" || arg == "-v"
        puts "kah 0.2.0 (Ruby compiled by Spinel; native support compiled by Nelua; Prism frontend)"
        return 0
      elsif arg == "--help" || arg == "-h"
        usage
        return 0
      elsif arg == "-o" || arg == "--output"
        i += 1
        return bad("#{arg} needs a file") if i >= args.length
        @output = args[i]
      elsif arg.start_with?("--output=")
        @output = arg[9, arg.length - 9]
      elsif arg == "-I"
        i += 1
        return bad("-I needs a directory") if i >= args.length
        @load_paths << args[i]
      elsif arg.start_with?("-I") && arg.length > 2
        @load_paths << arg[2, arg.length - 2]
      elsif arg == "-e"
        i += 1
        return bad("-e needs Ruby source") if i >= args.length
        @inline = @inline + "\n" + args[i]
        @inline_used = true
      elsif arg == "-E"
        @run = true
      elsif arg == "-S"
        @stdout = true
      elsif arg == "-c"
        # Lua source is already this backend's compile result.
      elsif arg == "--force"
        @force = true
      elsif arg.start_with?("--target=")
        @target = arg[9, arg.length - 9]
        return bad("unknown Lua target #{@target}") unless @target == "lua" || @target == "luajit"
      elsif arg.start_with?("--lua=")
        @interpreter = arg[6, arg.length - 6]
      elsif arg == "--"
        i += 1
        if @source.empty? && i < args.length
          @source = args[i]
          i += 1
        end
        while i < args.length
          @run_args << args[i]
          i += 1
        end
        break
      elsif arg.start_with?("-")
        return bad("unknown option #{arg}")
      elsif @source.empty?
        @source = arg
        if @run
          i += 1
          while i < args.length
            @run_args << args[i]
            i += 1
          end
          break
        end
      else
        return bad("unexpected argument #{arg}")
      end
      i += 1
    end
    return bad("-E cannot be combined with -o or -S") if @run && (!@output.empty? || @stdout)
    return bad("provide one Ruby file or -e") if @source.empty? && !@inline_used
    return bad("a source file cannot be combined with -e") if !@source.empty? && @inline_used
    path = @inline_used ? "(kah -e)" : @source
    source = @inline_used ? @inline : File.read(@source)
    ast = KahAST.new(source, path)
    generated = ""
    failed = false
    begin
      if ast.error_count > 0
        j = 0
        while j < ast.error_count
          STDERR.puts "kah: #{path}:#{ast.error_line(j)}: #{ast.error_message(j)}"
          j += 1
        end
        failed = true
      else
        compiler = KahLuaEmitter.new(ast, KahRuntime::SOURCE, @load_paths)
        generated = compiler.compile
        failed = compiler.failed
      end
    ensure
      ast.close
    end
    return 1 if failed
    if @stdout
      print generated
      return 0
    end
    run = @run || (@inline_used && @output.empty?)
    temporary = ""
    output = @output
    if run
      directory = ENV["TMPDIR"] || "/tmp"
      temporary = KahNative.kah_native_temp(directory)
      return bad("cannot create temporary Lua file") if temporary == nil
      output = temporary
    elsif output.empty?
      stem = File.basename(@source)
      stem = stem[0, stem.length - 3] if stem.end_with?(".rb")
      output = stem + ".lua"
    end
    unless run
      if !@inline_used && KahNative.kah_native_same_file(@source, output) != 0
        return bad("output would overwrite the Ruby input: #{output}")
      end
      if File.exist?(output) && !@force
        unless File.read(output).start_with?("-- Generated by Kah:")
          return bad("refusing to overwrite #{output}; use --force for a file Kah did not generate")
        end
      end
    end
    File.write(output, generated)
    unless run
      STDERR.puts "Wrote #{output}"
      return 0
    end
    interpreter = @interpreter.empty? ? @target : @interpreter
    packed = @run_args.join("\0") + "\0"
    status = 1
    begin
      status = KahNative.kah_native_run(interpreter, output, packed, packed.bytesize, @run_args.length)
    ensure
      File.delete(temporary)
    end
    status
  end
end

KahNative.kah_native_init
begin
  exit KahCLI.new.execute(ARGV)
rescue StandardError => error
  STDERR.puts "kah: #{error.message}"
  exit 1
end
