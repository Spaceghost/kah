# Embed Kah's Lua runtime so the native compiler stays self-contained.
source = File.binread(File.expand_path('../lib/kah_runtime.lua', __dir__))
puts '/* Generated by tools/gen_kah_runtime.rb. Edit lib/kah_runtime.lua. */'
source.each_line do |line|
  escaped = line.bytes.map do |byte|
    case byte
    when 34 then '\\"'
    when 92 then '\\\\'
    when 10 then '\\n'
    when 32..126 then byte.chr
    else format('\\%03o', byte)
    end
  end.join
  puts '"' + escaped + '"'
end
