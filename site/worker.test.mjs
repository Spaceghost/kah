import assert from 'node:assert/strict';
import test from 'node:test';
import worker from '../build/kah-site/worker.mjs';

const request = (path, options) => worker.fetch(new Request('https://spacegho.st' + path, options));

test('serves Kah and the guide, with bounded routes and correct MIME types', async () => {
  const home = request('/kah/');
  assert.equal(home.status, 200);
  assert.match(home.headers.get('Content-Type'), /text\/html/);
  const html = await home.text();
  assert.match(html, /Ruby, in/);
  assert.match(html, /Actual generated Lua excerpt/);
  assert.doesNotMatch(html, /illustrative|will follow the first/);
  const guide = request('/kah/docs');
  assert.match(await guide.text(), /9007199254740991/);
  assert.equal(request('/kah/not-found').status, 404);
  assert.equal(request('/unrelated').status, 404);
});

test('redirects the exact root while retaining query parameters', () => {
  const response = request('/kah?from=moon');
  assert.equal(response.status, 308);
  assert.equal(response.headers.get('Location'), 'https://spacegho.st/kah/?from=moon');
});

test('sets content headers and honors HEAD and conditional GET', async () => {
  const response = request('/kah/');
  assert.equal(response.headers.get('X-Content-Type-Options'), 'nosniff');
  const cached = request('/kah/', { headers: { 'If-None-Match': response.headers.get('ETag') } });
  assert.equal(cached.status, 304);
  assert.equal(await cached.text(), '');
  const head = request('/kah/', { method: 'HEAD' });
  assert.equal(head.status, 200);
  assert.equal(await head.text(), '');
  assert.equal(request('/kah/', { method: 'POST' }).status, 405);
});

test('publishes real generated Lua and Ruby examples', async () => {
  const lua = await request('/kah/examples/hello.lua').text();
  assert.match(lua, /^-- Generated by Kah:/);
  assert.match(lua, /local _R/);
  const ruby = await request('/kah/examples/hello.rb').text();
  assert.match(ruby, /def twice/);
});
